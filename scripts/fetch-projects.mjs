/**
 * Fetches GitHub repos and probes matching Netlify URLs.
 * Run before build: node scripts/fetch-projects.mjs
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const GITHUB_USER = 'The-Accolade';
const NETLIFY_TEAM = 'the-accolade';
const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '../src/data/projects.generated.js');

const EXCLUDE = new Set([
  'HelloWorld', 'hello-world', 'test', 'play', 'Morning-Challenge',
  'My-Morning-Challenge', 'Morning-Challenge-1-9-2020', 'Morning-Challenge-1-7-2020',
  'Morning-Challenge-12-12-19', 'todo-list-', 'Todo-List-App', 'random-jokes',
  'tip', 'tip-calculator', 'loan-calculator', 'Google-Search-Results-Clone-',
  'contacts', 'contactList', 'a-simple-react-form', 'mood-changer-redux',
  'asynchronous-redux-with-thunk', 'color-app', 'color-factory-app', 'todo-app-hooks',
  'ShoppingList', 'MyInstagram', 'instagram-clone', 'Chat', 'natours-advanced-css-project',
  'PostIt', 'algorithms', 'getting-back', 'e-report', 'tik-tok-clone', 'PERN-TodoApp',
  'portfolio', // superseded by this site; portfolio.netlify.app is not owned by us
]);

const NETLIFY_PATTERNS = (name) => [
  `https://${name}.netlify.app`,
  `https://${name}--${NETLIFY_TEAM}.netlify.app`,
  `https://${NETLIFY_TEAM}-${name}.netlify.app`,
];

async function fetchRepos() {
  const res = await fetch(
    `https://api.github.com/users/${GITHUB_USER}/repos?per_page=100&sort=updated&type=owner`
  );
  if (!res.ok) throw new Error(`GitHub API error: ${res.status}`);
  return res.json();
}

const GENERIC_SLUGS = new Set(['portfolio', 'company-website', 'demo', 'test', 'play']);

async function verifySite(url, repoName) {
  try {
    const res = await fetch(url, { redirect: 'follow', signal: AbortSignal.timeout(8000) });
    if (!res.ok) return false;
    const html = (await res.text()).slice(0, 20000).toLowerCase();
    const slug = repoName.toLowerCase();
    return (
      html.includes('the-accolade') ||
      html.includes('akolade') ||
      html.includes('kolade') ||
      html.includes(slug)
    );
  } catch {
    return false;
  }
}

async function probeLiveUrl(name) {
  const slug = name.toLowerCase();
  for (const url of NETLIFY_PATTERNS(name)) {
    try {
      const res = await fetch(url, { method: 'HEAD', redirect: 'follow', signal: AbortSignal.timeout(5000) });
      if (!res.ok) continue;
      if (GENERIC_SLUGS.has(slug) && !(await verifySite(url, name))) continue;
      return url;
    } catch {
      /* try next pattern */
    }
  }
  return null;
}

function inferTopics(language, description) {
  const topics = language ? [language] : [];
  const text = `${description || ''}`.toLowerCase();
  if (text.includes('mern') || text.includes('mongo')) topics.push('MongoDB');
  if (text.includes('react')) topics.push('React');
  if (text.includes('node')) topics.push('Node.js');
  if (text.includes('next')) topics.push('Next.js');
  if (text.includes('vue')) topics.push('Vue.js');
  if (text.includes('firebase')) topics.push('Firebase');
  if (text.includes('socket')) topics.push('Socket.io');
  return [...new Set(topics)];
}

async function main() {
  const repos = await fetchRepos();
  const candidates = repos
    .filter((r) => !r.fork && !EXCLUDE.has(r.name))
    .sort((a, b) => new Date(b.updated_at) - new Date(a.updated_at));

  const projects = [];

  for (const repo of candidates) {
    const liveUrl = await probeLiveUrl(repo.name);
    projects.push({
      name: repo.name.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()),
      slug: repo.name,
      description: repo.description || 'A project from The-Accolade GitHub portfolio.',
      language: repo.language,
      topics: inferTopics(repo.language, repo.description),
      githubUrl: repo.html_url,
      liveUrl,
      updatedAt: repo.updated_at.slice(0, 10),
    });
  }

  projects.sort((a, b) => {
    if (a.liveUrl && !b.liveUrl) return -1;
    if (!a.liveUrl && b.liveUrl) return 1;
    return b.updatedAt.localeCompare(a.updatedAt);
  });

  const featured = projects.filter((p) => p.liveUrl || p.description.length > 30).slice(0, 12);

  const content = `/* Auto-generated by scripts/fetch-projects.mjs — do not edit */
export const PROJECTS_META = {
  githubUser: '${GITHUB_USER}',
  netlifyTeam: '${NETLIFY_TEAM}',
  netlifyTeamUrl: 'https://app.netlify.com/teams/${NETLIFY_TEAM}/projects',
  fetchedAt: '${new Date().toISOString().slice(0, 10)}',
};

export const PROJECTS = ${JSON.stringify(featured, null, 2)};
`;

  writeFileSync(OUTPUT, content);
  const liveCount = featured.filter((p) => p.liveUrl).length;
  console.log(`Generated ${featured.length} projects (${liveCount} with live Netlify demos)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
